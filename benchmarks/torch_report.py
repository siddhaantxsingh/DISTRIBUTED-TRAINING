"""Render benchmarks/results/<date>/torch/summary.json as Markdown (printed to stdout).

    python benchmarks/torch_report.py benchmarks/results/2026-10-15/torch > docs/torch_crosscheck_tables.md
"""
import json
import sys
from collections import defaultdict

import numpy as np


def e(x):
    return f"{x:.1e}" if x else "0"


def main(d):
    s = json.load(open(f"{d}/summary.json"))
    p = print
    p(f"<!-- generated by benchmarks/torch_report.py from {d}/summary.json -->")
    p(f"torch {s['torch']}, numpy {s['numpy']}, {s['steps']} steps per equivalence run. "
      f"Load average (1/5/15 min) before: {' / '.join(s['load_before'])}, after: {' / '.join(s['load_after'])}.\n")

    p("### Collective alone: dtrain ring all-reduce vs gloo all_reduce, identical inputs\n")
    p("| W | dtype | max abs diff | bit-identical | max abs error vs exact sum: dtrain / gloo |")
    p("|---|---|---|---|---|")
    for c in s["collective"]:
        for dt in ("float32", "float64"):
            x = c[dt]
            p(f"| {c['world']} | {dt} | {e(x['max_abs_diff_dtrain_vs_gloo'])} | {x['bit_identical_frac']*100:.1f} % | "
              f"{e(x['max_abs_err_dtrain'])} / {e(x['max_abs_err_gloo'])} |")

    p("\n### Optimizer alone: dtrain AdamW vs torch.optim.AdamW, identical gradients\n")
    for dt, x in s["adamw_only"].items():
        p(f"- {dt}: max abs parameter difference over {len(x['param_maxabs_diff_per_step'])} steps "
          f"{e(x['param_maxabs_diff_max'])}")

    p("\n### Training step by step: dtrain vs PyTorch\n")
    p("`ddp`: dtrain DDP + AdamW vs torch DDP + AdamW. `ddp-sgd`: plain SGD (lr 0.1), so parameter differences "
      "are only lr × gradient differences. `zero`: dtrain ZeroAdamW vs torch DDP + ZeroRedundancyOptimizer(AdamW).\n")
    p("| mode | W | dtype | max grad diff (any step) | max param diff: step 1 / last / max | max loss diff | final loss dtrain / torch |")
    p("|---|---|---|---|---|---|---|")
    for x in s["equivalence"]:
        ps = x["param_maxabs_diff_per_step"]
        g = e(x["grad_maxabs_diff_max"]) if "grad_maxabs_diff_max" in x else "n/a"
        p(f"| {x['mode']} | {x['world']} | {x['dtype']} | {g} | {e(ps[0])} / {e(ps[-1])} / {e(max(ps))} | "
          f"{e(x['loss_abs_diff_max'])} | {x['final_loss_dtrain']:.6f} / {x['final_loss_torch']:.6f} |")

    p("\n### ZeRO-1 optimizer state per rank (bytes)\n")
    p("| W | dtype | dtrain per rank | torch ZeroRedundancyOptimizer per rank |")
    p("|---|---|---|---|")
    for x in s["equivalence"]:
        if x["mode"] == "zero":
            sb = x["state_bytes_per_rank"]
            p(f"| {x['world']} | {x['dtype']} | {', '.join(str(r['dtrain_state_bytes']) for r in sb)} | "
              f"{', '.join(str(r['torch_state_bytes']) for r in sb)} |")

    p("\n### Checkpoint, exit, resume in new processes\n")
    p("| mode | W | dtype | steps (ckpt at) | dtrain resumed == uninterrupted | torch resumed == uninterrupted | dtrain vs torch after resume |")
    p("|---|---|---|---|---|---|---|")
    for x in s["resume"]:
        p(f"| {x['mode']} | {x['world']} | {x['dtype']} | {x['steps']} ({x['ckpt_step']}) | "
          f"{'bit-identical' if x['dtrain_resumed_bit_identical'] else 'DIFFERENT'} | "
          f"{'bit-identical' if x['torch_resumed_bit_identical'] else 'DIFFERENT'} | {e(x['dtrain_vs_torch_resumed_maxabs'])} |")

    if s["throughput"]:
        p("\n### Throughput: float32 GPT (dim 128, 4 layers, ctx 64, 8 seq/rank), DDP, 1 thread per rank\n")
        p("Median step time over steps 6–30; tokens/s is the median of the repeats (min–max in brackets).\n")
        p("| W | dtrain tokens/s | torch DDP (gloo) tokens/s | torch / dtrain |")
        p("|---|---|---|---|")
        agg = defaultdict(list)
        for r in s["throughput"]:
            agg[(r["impl"], r["world"])].append(r["tokens_per_s"])
        for w in sorted({r["world"] for r in s["throughput"]}):
            dd, tt = agg[("dtrain", w)], agg[("torch", w)]
            p(f"| {w} | {np.median(dd):,.0f} ({min(dd):,.0f}–{max(dd):,.0f}) | {np.median(tt):,.0f} "
              f"({min(tt):,.0f}–{max(tt):,.0f}) | {np.median(tt)/np.median(dd):.1f}× |")
        p("\nLoad averages around each run: " + "; ".join(
            f"{r['impl']} W={r['world']} r{r['repeat']}: {r['load_before'][0]}" for r in s["throughput"]) + ".")

    if s["allreduce_speed"]:
        p("\n### All-reduce latency, float32: dtrain ring vs gloo (median of repeats)\n")
        p("| W | size | dtrain ring | gloo | gloo bus BW |")
        p("|---|---|---|---|---|")
        agg = defaultdict(list)
        for r in s["allreduce_speed"]:
            agg[(r["world"], r["bytes"], r["impl"])].append(r)
        for w in (2, 4):
            for b in sorted({r["bytes"] for r in s["allreduce_speed"]}):
                d_ = agg[(w, b, "dtrain-ring")]
                g_ = agg[(w, b, "gloo")]
                if not d_:
                    continue
                dl = np.median([r["latency_us"] for r in d_])
                gl = np.median([r["latency_us"] for r in g_])
                gb = np.median([r["bus_GBps"] for r in g_])
                size = f"{b >> 20} MiB" if b >= 1 << 20 else f"{b >> 10} KiB"
                p(f"| {w} | {size} | {dl:,.0f} µs | {gl:,.0f} µs | {gb:.2f} GB/s |")


if __name__ == "__main__":
    main(sys.argv[1])
